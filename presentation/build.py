"""Embed report data in a local script: works via file:// without a server."""
import hashlib
import json
import subprocess
import sys
from pathlib import Path


def main():
    root = Path(__file__).resolve().parents[1]
    subprocess.run([sys.executable, str(root / "scripts/build_flow_docs.py")], check=True, cwd=root)
    if "--flows-only" in sys.argv:
        return
    paths = {
        "main": "src/reports/benchmark.json", "public": "src/reports/bonus_public.json",
        "adversarial": "src/reports/bonus_adversarial.json", "safety": "src/reports/bonus_safety.json",
        "crash": "src/reports/crash.json", "example": "src/reports/bonus_trace_example.json",
    }
    if (root / "src/reports/hidden_summary.json").is_file():
        paths["hidden"] = "src/reports/hidden_summary.json"
    payload = {key: json.loads((root / path).read_text(encoding="utf-8")) for key, path in paths.items()}
    # Match the repository's eol=lf even when Windows CLI output uses CRLF.
    payload["sources"] = {key: {"path": path, "hash_normalization": "LF",
                              "sha256": hashlib.sha256((root / path).read_bytes().replace(b"\r\n", b"\n")).hexdigest()}
                          for key, path in paths.items()}
    payload["cases"] = {}
    for name, path in [("public", "src/data/public_claims.jsonl"), ("adversarial", "src/bonus/cases.jsonl")]:
        rows = [json.loads(line) for line in (root / path).read_text(encoding="utf-8").splitlines() if line]
        # Display only safe, intentional fixture facts. No parent context or PII.
        payload["cases"][name] = [{k: row[k] for k in ("claim_id", "matrix_id", "title") if k in row}
                                   for row in rows]
    body = json.dumps(payload, ensure_ascii=False).replace("<", "\\u003c")
    (root / "presentation/data.js").write_text("// Generated by python -m presentation.build\nwindow.LAB_DATA = " + body + ";\n", encoding="utf-8")
    print("Built presentation/data.js from real reports (no network required)")


if __name__ == "__main__":
    main()
